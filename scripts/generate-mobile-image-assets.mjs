import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const source=path.join(root,"apps/web/public/source-images");
const out=path.join(root,"apps/mobile/src/image-assets.ts");
const supported=/\.(png|jpe?g|webp)$/i;
function walk(dir){if(!fs.existsSync(dir))return[];return fs.readdirSync(dir,{withFileTypes:true}).flatMap((entry)=>{const full=path.join(dir,entry.name);return entry.isDirectory()?walk(full):supported.test(entry.name)?[full]:[]})}
const files=walk(source).map((file)=>path.relative(source,file).split(path.sep).join("/")).sort((a,b)=>a.localeCompare(b,"en"));
const lines=["// Generated by scripts/generate-mobile-image-assets.mjs. Do not edit by hand.","export const imageAssets: Record<string, number> = {"];
for(const key of files){const rel="../../web/public/source-images/"+key;lines.push(`  ${JSON.stringify(key)}: require(${JSON.stringify(rel)}),`)}
lines.push("};","");
fs.mkdirSync(path.dirname(out),{recursive:true});
fs.writeFileSync(out,lines.join("\n"));
console.log(`Generated ${files.length} mobile publication image assets.`);
